function isoDate(dateVal) {
  const d = new Date(dateVal);
  const month = String(d.getUTCMonth() + 1).padStart(2, '0');
  const day = String(d.getUTCDate()).padStart(2, '0');
  return `${d.getUTCFullYear()}-${month}-${day}`;
}

// ---- _redirects -------------------------------------------------------------
//
// The old WordPress permalink structure was `/%postname%/` — read out of
// `permalink_structure` in the Duplicator dump — so every recovered post was
// indexed at a root-level slug, not under /blog/ (SEO-REVIEW-2026-10-21.md §1).
// Republishing one at /blog/<slug> with no 301 from its old URL hands Google a
// brand-new page and leaves the indexed URL dead: the content comes back, the
// equity does not.
//
// So these rules are generated from the same published-post list the sitemap
// is built from, never hand-maintained. A post cannot be published without its
// redirect appearing, and a post that goes back to draft loses it again —
// a 301 to a page that does not exist is worse than the 404 it replaces.
//
// Only a post that actually had an old URL carries `legacy_path`. The six 2026
// posts never lived on WordPress, and the 14 recovered WordPress *drafts* were
// never published there, so neither gets a rule. That distinction is the whole
// point for `keep-moving-forward`: /keep-moving-forward/ was the 2016 post, so
// pointing it at the unrelated 2026 post of the same slug would be a wrong
// answer rather than a recovery. The 2016 post is held at
// blog/posts/keep-moving-forward-2016-10-26.md and carries the old path.
//
// Both /<slug>/ and /<slug> are emitted: Cloudflare matches the source path as
// written and does not normalise the trailing slash, which is why the
// hand-written rules list both forms too.
//
// Everything above the markers stays hand-written. Those are editorial calls
// reviewed against Search Console — including the deliberate decision not to
// redirect dead posts to the blog index, which still holds for every post that
// stays a draft.
//
// Cloudflare Pages caps the file at 2,000 static redirects. All 279 recovered
// WordPress posts published at once is 558 rules, plus the 6 hand-written ones:
// 564, comfortably inside the cap, so this scales to the whole archive.
const REDIRECTS_PATH = path.join(__dirname, '_redirects');
const REDIRECTS_START = '# ARCHIVE-REDIRECTS:START (auto-generated by build-blog.js — do not edit by hand)';
const REDIRECTS_END = '# ARCHIVE-REDIRECTS:END';
const STATIC_REDIRECT_LIMIT = 2000;

// The `from` column of every rule outside the generated block. Cloudflare
// applies the top-most rule when two share a source, and the hand-written ones
// sit above the block, so a clash would silently swallow a generated redirect.
function handWrittenSources(preserved) {
  const sources = new Set();
  for (const line of preserved.split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    sources.add(trimmed.split(/\s+/)[0]);
  }
  return sources;
}

function buildRedirects(posts) {
  const before = fs.readFileSync(REDIRECTS_PATH, 'utf8');
  const re = /# ARCHIVE-REDIRECTS:START[\s\S]*?# ARCHIVE-REDIRECTS:END/;
  if (!re.test(before)) {
    // Not a skip like the NAV/FOOTER markers: silently shipping no archive
    // redirects is the exact failure this function exists to prevent.
    throw new Error('_redirects: ARCHIVE-REDIRECTS markers not found — restore them, the build fills the block between them');
  }
  const reserved = handWrittenSources(before.replace(re, ''));

  const legacy = posts.filter(p => p.legacyPath);
  const seen = new Map();
  const pairs = [];

  for (const p of legacy) {
    const from = p.legacyPath;
    if (!/^\/[^\s#]+\/$/.test(from)) {
      throw new Error(`${p.slug}: legacy_path must be a root-absolute path with a trailing slash, got "${from}"`);
    }
    const bare = from.slice(0, -1);
    if (bare.startsWith('/blog')) {
      throw new Error(`${p.slug}: legacy_path "${from}" is under /blog/, where the post itself is served`);
    }
    if (seen.has(from)) {
      throw new Error(`legacy_path "${from}" is claimed by both ${seen.get(from)} and ${p.slug}`);
    }
    seen.set(from, p.slug);
    for (const source of [from, bare]) {
      if (reserved.has(source)) {
        throw new Error(`${p.slug}: legacy_path "${from}" collides with the hand-written rule for "${source}"`);
      }
      pairs.push([source, `/blog/${p.slug}`]);
    }
  }

  const total = pairs.length + reserved.size;
  if (total > STATIC_REDIRECT_LIMIT) {
    throw new Error(`_redirects: ${total} static rules exceeds Cloudflare's limit of ${STATIC_REDIRECT_LIMIT}`);
  }

  // Same column layout as the hand-written rules above.
  const width = pairs.reduce((w, [source]) => Math.max(w, source.length), 0) + 2;
  const rules = pairs.map(([source, target]) => `${source.padEnd(width)}${target}   301`);

  const block = [REDIRECTS_START, ...rules, REDIRECTS_END].join('\n');
  const after = before.replace(re, () => block);
  if (after !== before) fs.writeFileSync(REDIRECTS_PATH, after);
  console.log(`  built  _redirects (${rules.length} archive rules for ${legacy.length} posts, ${total}/${STATIC_REDIRECT_LIMIT} static)`);
}

// ---- Asset versioning -------------------------------------------------------
//
// styles.css, vendor/tokens.css and site.js are served with
// `cache-control: public, max-age=14400`, while the HTML is `max-age=0`. A
// returning visitor therefore picks up new markup at once and keeps the old
// stylesheet for up to four hours. That is not theoretical: the paginated blog
// index shipped on 21 Oct 2026 and rendered as unstyled blue links for anyone
// who had loaded the site earlier that day — new HTML, four-hour-old CSS.
//
// So the HTML asks for the file by content hash. A changed asset is a changed
// URL, which no browser has cached, and the stale copy is simply never
// requested again. An unchanged asset keeps its URL and stays cached — the
// hash is of the bytes, not of the build.
//
// Every HTML file is rewritten, not just the generated ones: a hand-authored
// page with no partial markers still links the stylesheet, and a query string
// on that link changes nothing visually, so there is no reason to leave it stale.
const VERSIONED_ASSETS = ['styles.css', 'vendor/tokens.css', 'site.js', 'blog-search.js'];

// Source, not output: partials/ is inlined into the pages (and versioned
// there), admin/ is the CMS and loads its own bundle from a CDN.
const VERSION_SKIP_DIRS = new Set([
  'node_modules', '.git', '.github', '.claude', 'test-results', 'tests', 'partials', 'admin', 'vendor',
  'pagefind',
]);

function assetVersions() {
  const versions = {};
  for (const rel of VERSIONED_ASSETS) {
    const file = path.join(__dirname, rel);
    if (!fs.existsSync(file)) throw new Error(`versioned asset missing: ${rel}`);
    const bytes = fs.readFileSync(file);
    versions[rel] = crypto.createHash('sha256').update(bytes).digest('hex').slice(0, 8);
  }
  return versions;
}

// Anchored on the opening quote so a prefix cannot be matched loosely — a
// bare `styles.css` pattern would otherwise match the tail of `mystyles.css`.
// An existing ?v= is replaced, which is what makes a rebuild idempotent.
function versionAssetLinks(html, versions) {
  let out = html;
  for (const [rel, hash] of Object.entries(versions)) {
    const escaped = rel.replace(/\./g, '\\.');
    const re = new RegExp(`(href|src)="((?:\\.\\./)*|/)${escaped}(?:\\?v=[0-9a-f]+)?"`, 'g');
    out = out.replace(re, (_m, attr, prefix) => `${attr}="${prefix}${rel}?v=${hash}"`);
  }
  return out;
}

function versionAssetsEverywhere(versions) {
  const files = [];
  (function walk(dir) {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      if (entry.isDirectory()) {
        if (VERSION_SKIP_DIRS.has(entry.name)) continue;
        walk(path.join(dir, entry.name));
      } else if (entry.name.endsWith('.html')) {
        files.push(path.join(dir, entry.name));
      }
    }
  })(__dirname);

  let changed = 0;
  const unversioned = [];
  for (const file of files) {
    const before = fs.readFileSync(file, 'utf8');
    const after = versionAssetLinks(before, versions);
    if (after !== before) {
      fs.writeFileSync(file, after);
      changed++;
    }
    // Anything still bare means a reference this pass does not understand —
    // a new asset, or a path shape the pattern misses. Caching it hard would
    // be the very bug this exists to prevent, so fail loudly.
    for (const rel of VERSIONED_ASSETS) {
      const escaped = rel.replace(/\./g, '\\.');
      if (new RegExp(`(href|src)="((?:\\.\\./)*|/)?${escaped}"`).test(after)) {
        unversioned.push(`${path.relative(__dirname, file)} -> ${rel}`);
      }
    }
  }
  if (unversioned.length) {
    throw new Error(`unversioned asset reference(s) left behind:\n  ${unversioned.join('\n  ')}`);
  }

  const summary = Object.entries(versions).map(([rel, h]) => `${rel}=${h}`).join(' ');
  console.log(`  built  asset versions in ${files.length} page(s), ${changed} rewritten (${summary})`);
}

// sitemap.xml is generated, never hand-edited — editing it by hand is how it
// went stale. The homepage and blog index both change whenever a post is
// published, so their lastmod tracks the newest post.
function buildSitemap(posts, indexPages, topicPages) {
  const newest = posts.length ? isoDate(posts[0].data.date) : isoDate(Date.now());

  const urls = [
    { path: '/', lastmod: newest },
    // Every index page, not just /blog/. They are real indexable pages with
    // their own canonicals, and listing them gives the crawler the whole
    // archive without having to walk prev/next links. Each one's lastmod is
    // the newest post it lists.
    ...indexPages.map(pg => ({
      path: pg.path,
      lastmod: pg.newest ? isoDate(pg.newest.data.date) : newest,
    })),
    ...posts.map(p => ({ path: `/blog/${p.slug}`, lastmod: isoDate(p.data.date) })),
    // Held back until the topic names are approved (TOPIC_PAGES_INDEXED).
    ...(TOPIC_PAGES_INDEXED ? topicPages : []).map(t => ({ path: t.path, lastmod: isoDate(t.newest.data.date) })),
    ...STATIC_PAGES,
  ];

  const body = urls.map(u => [
    '  <url>',
    `    <loc>${SITE_ORIGIN}${u.path}</loc>`,
    `    <lastmod>${u.lastmod}</lastmod>`,
    '  </url>',
  ].join('\n')).join('\n');

  const xml = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${body}
</urlset>
`;

  fs.writeFileSync(path.join(__dirname, 'sitemap.xml'), xml);
  console.log(`  built  sitemap.xml (${urls.length} urls)`);
}

// ---- Search index ----------------------------------------------------------
//
// Full-text search on /blog/ runs on Pagefind: it splits the index into small
// chunks at build time, and the browser fetches only the chunks a query needs.
// The whole archive is ~230,000 words, far too much to ship as one JSON file
// to a phone.
//
// Posts go in as custom records built from the data already in hand, rather
// than by crawling the generated HTML, so the post pages carry no Pagefind
// attributes and none of them change. Drafts never reach `posts`, so an
// unpublished post drops out of the index on the next build along with its page.
//
// The output directory is deleted first: Pagefind names its chunks by content
// hash, and chunks from a previous build would otherwise pile up in the repo.
const SEARCH_DIR = path.join(__dirname, 'pagefind');

function plainText(html) {
  return html
    .replace(/<[^>]+>/g, ' ')
    .replace(/&nbsp;/g, ' ')
    .replace(/&#39;/g, "'")
    .replace(/&quot;/g, '"')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&amp;/g, '&')
    .replace(/\s+/g, ' ')
    .trim();
}

async function buildSearchIndex(posts) {
  const pagefind = await import('pagefind');
  const { index, errors } = await pagefind.createIndex({ forceLanguage: 'en' });
  if (!index) throw new Error(`pagefind: ${errors.join('; ')}`);

  for (const p of posts) {
    const { errors: recordErrors } = await index.addCustomRecord({
      url: `/blog/${p.slug}`,
      content: `${p.data.title}. ${plainText(p.body)}`,
      language: 'en',
      meta: {
        title: p.data.title,
        type: p.data.type,
        date: p.displayDate,
        excerpt: p.data.excerpt,
      },
      filters: {
        topic: p.data.topics || [],
        year: [String(new Date(p.data.date).getUTCFullYear())],
      },
      sort: { date: isoDate(p.data.date) },
    });
    if (recordErrors.length) throw new Error(`pagefind: ${p.slug}: ${recordErrors.join('; ')}`);
  }

  fs.rmSync(SEARCH_DIR, { recursive: true, force: true });
  const { errors: writeErrors } = await index.writeFiles({ outputPath: SEARCH_DIR });
  if (writeErrors.length) throw new Error(`pagefind: ${writeErrors.join('; ')}`);
  await pagefind.close();
  console.log(`  built  pagefind/ search index (${posts.length} posts)`);
}

// Every published post, newest first, plus the slugs of the drafts so a hub
// that names one can say so.
function readPosts() {
  const files = fs.readdirSync(POSTS_DIR).filter(f => f.endsWith('.md'));
  const posts = [];
  const draftSlugs = new Set();

  for (const file of files) {
    const result = buildPost(path.join(POSTS_DIR, file));
    if (result) posts.push(result);
    else draftSlugs.add(path.basename(file, '.md'));
  }

  posts.sort((a, b) => new Date(b.data.date) - new Date(a.data.date));
  return { posts, draftSlugs };
}

function main() {
  const { posts, draftSlugs } = readPosts();

  // Validated before anything is written, so a bad hub leaves the site as it was.
  const hubs = readHubs();
  validateHubs(hubs, posts, draftSlugs);
  // Biggest topic first in the blog index's topic links.
  const postsOn = (topic) => posts.filter(p => (p.data.topics || []).includes(topic)).length;
  hubs.sort((a, b) => postsOn(b.topic) - postsOn(a.topic) || a.topic.localeCompare(b.topic));

  const activeSlugs = new Set(posts.map(p => p.slug));
  const existingHtml = fs.readdirSync(BLOG_DIR).filter(f =>
    f.endsWith('.html') && f !== 'index.html' && f !== '_template.html'
  );
  for (const file of existingHtml) {
    const slug = file.replace(/\.html$/, '');
    if (!activeSlugs.has(slug)) {
      fs.unlinkSync(path.join(BLOG_DIR, file));
      console.log(`  removed  ${file} (no matching .md source)`);
    }
  }

  for (const post of posts) {
    const outPath = path.join(BLOG_DIR, `${post.slug}.html`);
    fs.writeFileSync(outPath, post.html);
    console.log(`  built  ${post.slug}.html`);
  }

  const indexPages = buildIndexPages(posts, hubs);
  const topicPages = buildTopicPages(posts, hubs);

  buildHomepageInsights(posts);
  inlineStaticPages();
  buildSitemap(posts, indexPages, topicPages);
  buildRedirects(posts);
  versionAssetsEverywhere(assetVersions());

  buildSearchIndex(posts).catch((err) => {
    console.error(err);
    process.exit(1);
  });
}

