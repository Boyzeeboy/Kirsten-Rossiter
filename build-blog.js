const marked = new Marked();

const renderer = new marked.Renderer();

let isFirstParagraph = true;

renderer.paragraph = function ({ tokens }) {
  const text = this.parser.parseInline(tokens);
  if (isFirstParagraph) {
    isFirstParagraph = false;
    return `<p class="lead">${text}</p>\n`;
  }
  return `<p>${text}</p>\n`;
};

marked.use({ renderer });

function formatDate(dateVal) {
  const d = new Date(dateVal);
  const day = d.getUTCDate();
  const months = [
    'January', 'February', 'March', 'April', 'May', 'June',
    'July', 'August', 'September', 'October', 'November', 'December'
  ];
  return `${day} ${months[d.getUTCMonth()]} ${d.getUTCFullYear()}`;
}

function escapeHtml(str) {
  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

// ---- Shared chrome ---------------------------------------------------------
//
// The nav and footer ship in the HTML. They used to arrive by fetch() after
// load (includes.js), which meant the served page carried no internal links at
// all — contact.html was an orphan to every crawler that does not run
// JavaScript (SEO-AUDIT.md #3). partials/*.html remain the single source of
// truth; the build copies each one between a pair of marker comments in every
// page, generated or hand-authored, and replaces only what sits between the
// markers. Same pattern as the homepage insights block. Hand-authored pages
// are never rewritten wholesale.
//
// terms.html and 404.html carry their own older nav, with no drawer, and are
// not walked. Moving them onto the partial changes what they look like, so it
// is a separate change with its own baseline update.
const PARTIALS_DIR = path.join(__dirname, 'partials');
const PARTIALS = { NAV: 'nav.html', FOOTER: 'footer.html' };
const partialCache = {};

function readPartial(name) {
  if (!partialCache[name]) {
    const raw = fs.readFileSync(path.join(PARTIALS_DIR, PARTIALS[name]), 'utf8');
    // The file opens with a comment about itself. It belongs to the partial,
    // not to every page it lands in.
    partialCache[name] = raw.replace(/^\s*<!--[\s\S]*?-->\s*/, '').trim();
  }
  return partialCache[name];
}

function partialBlock(name) {
  return [
    `<!-- ${name}:START (auto-generated by build-blog.js from partials/${PARTIALS[name]} — do not edit by hand) -->`,
    readPartial(name),
    `<!-- ${name}:END -->`,
  ].join('\n');
}

function inlinePartials(html) {
  let out = html;
  for (const name of Object.keys(PARTIALS)) {
    const re = new RegExp(`<!-- ${name}:START[\\s\\S]*?<!-- ${name}:END -->`, 'g');
    // Function form, so a $ in the partial is never read as a replacement pattern.
    out = out.replace(re, () => partialBlock(name));
  }
  return out;
}

// Hand-authored pages that carry the markers. blog/_template.html is reachable
// live (SEO-AUDIT.md #7), so it gets the same treatment rather than a stale
// data-include that nothing fills any more.
const STATIC_HTML = ['index.html', 'contact.html', 'building-the-nations.html', 'blog/_template.html'];

function inlineStaticPages() {
  for (const rel of STATIC_HTML) {
    const file = path.join(__dirname, rel);
    if (!fs.existsSync(file)) {
      console.log(`  skipped  ${rel} (not found)`);
      continue;
    }
    const before = fs.readFileSync(file, 'utf8');
    if (!/<!-- NAV:START/.test(before) || !/<!-- FOOTER:START/.test(before)) {
      console.log(`  skipped  ${rel} (NAV/FOOTER markers not found)`);
      continue;
    }
    const after = inlinePartials(before);
    if (after !== before) {
      fs.writeFileSync(file, after);
      console.log(`  inlined  ${rel}`);
    }
  }
}

