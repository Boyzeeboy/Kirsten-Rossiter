function buildTopicPages(posts, hubs) {
  const topics = [...new Set(posts.flatMap(p => p.data.topics || []))].sort();
  const built = [];
  fs.mkdirSync(TOPIC_DIR, { recursive: true });

  for (const topic of topics) {
    const topicPosts = posts.filter(p => (p.data.topics || []).includes(topic));
    const hub = hubs.find(h => h.topic === topic);
    const file = `${topicSlug(topic)}.html`;
    fs.writeFileSync(path.join(TOPIC_DIR, file), buildTopicPage(topic, topicPosts, hub));
    built.push({ topic, file, path: topicPath(topic), newest: topicPosts[0] });
  }

  // A topic nobody uses any more, or one that was renamed, would otherwise
  // leave its old page behind, listing posts that have moved on.
  const current = new Set(built.map(t => t.file));
  for (const file of fs.readdirSync(TOPIC_DIR).filter(f => f.endsWith('.html'))) {
    if (!current.has(file)) {
      fs.unlinkSync(path.join(TOPIC_DIR, file));
      console.log(`  removed  topics/${file} (no published post carries it)`);
    }
  }

  console.log(`  built  ${built.length} topic page(s), ${hubs.length} with a hub (${TOPIC_PAGES_INDEXED ? 'indexed' : 'noindex, not in sitemap'})`);
  return built;
}

function buildHomepageInsights(posts) {
  const INDEX_PATH = path.join(__dirname, 'index.html');

  if (!fs.existsSync(INDEX_PATH)) {
    console.log('  skipped  index.html (not found)');
    return;
  }

  const latest = posts.slice(0, 3);
  if (latest.length === 0) return;

  const ind = ' '.repeat(20); // match indentation inside .insights-featured

  const cards = latest.map((p, i) => {
    const url = `/blog/${p.slug}`;
    const label = escapeHtml(p.data.type || 'Prophetic Insight');
    const title = escapeHtml(p.data.title);

    if (i === 0) {
      return [
        `${ind}<div class="insight-card featured">`,
        `${ind}    <div class="insight-type">${label}</div>`,
        `${ind}    <h3 class="insight-title">${title}</h3>`,
        `${ind}    <p class="insight-excerpt">${escapeHtml(p.data.excerpt)}</p>`,
        `${ind}    <a href="${url}" class="insight-link">Read the revelation →</a>`,
        `${ind}</div>`,
      ].join('\n');
    }

    return [
      `${ind}<div class="insight-card">`,
      `${ind}    <div class="insight-type">${label}</div>`,
      `${ind}    <h3 class="insight-title">${title}</h3>`,
      `${ind}    <a href="${url}" class="insight-link">Read →</a>`,
      `${ind}</div>`,
    ].join('\n');
  }).join('\n');

  const startMarker = '<!-- INSIGHTS:START (auto-generated by build-blog.js — do not edit by hand) -->';
  const endMarker = '<!-- INSIGHTS:END -->';
  const block = `${startMarker}\n${cards}\n${ind}${endMarker}`;

  const html = fs.readFileSync(INDEX_PATH, 'utf8');
  const re = /<!-- INSIGHTS:START[\s\S]*?<!-- INSIGHTS:END -->/;

  if (!re.test(html)) {
    console.log('  skipped  index.html (INSIGHTS markers not found)');
    return;
  }

  fs.writeFileSync(INDEX_PATH, html.replace(re, block));
  console.log(`  built  index.html insights (${latest.length} cards)`);
}

